from __future__ import annotations

import json
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from pydantic import BaseModel, ConfigDict


@dataclass(frozen=True)
class ExplainabilityMetadata:
    analysis_name: str
    model_name: str
    target: str
    features: tuple[str, ...]
    evaluation_period: Mapping[str, Any]
    evaluation_metrics: Mapping[str, float]
    generated_at_utc: str
    limitations: tuple[str, ...]


@dataclass(frozen=True)
class GlobalImportance:
    feature: str
    importance_mean_mae_increase: float
    importance_std: float


@dataclass(frozen=True)
class CropSeasonErrorGroup:
    crop: str
    season: str
    observations: int
    mae: float
    rmse: float


@dataclass(frozen=True)
class PredictionBiasGroup:
    crop: str
    season: str
    observations: int
    mean_signed_error: float
    mean_bias_pct_of_actual: float | None


@dataclass(frozen=True)
class ScenarioBaseline:
    crop: str
    season: str
    crop_category: str
    state: str
    district: str
    fe_year_start: int
    baseline_prediction: float


class ExplainabilityService:
    """Service for serving explainability analysis from Notebook 21.

    This service loads and serves the pre-computed explainability summary
    generated by Notebook 21: Model Explainability and Scenario Analysis.

    It does NOT perform real-time explainability computations. All results
    are from the original notebook analysis on a 3000-sample evaluation
    dataset from 2021-2022.
    """

    def __init__(
        self,
        explainability_summary_path: Path,
    ) -> None:
        self._explainability_summary_path = explainability_summary_path
        self._summary: dict[str, Any] | None = None
        self._metadata: ExplainabilityMetadata | None = None

    def _load_summary(self) -> dict[str, Any]:
        if self._summary is not None:
            return self._summary

        if not self._explainability_summary_path.is_file():
            raise FileNotFoundError(
                f"Explainability summary not found: {self._explainability_summary_path}"
            )

        try:
            with open(self._explainability_summary_path, "r", encoding="utf-8") as f:
                self._summary = json.load(f)
        except (OSError, json.JSONDecodeError) as e:
            raise RuntimeError("Failed to load explainability summary") from e

        return self._summary

    def _get_metadata(self) -> ExplainabilityMetadata:
        if self._metadata is not None:
            return self._metadata

        summary = self._load_summary()

        self._metadata = ExplainabilityMetadata(
            analysis_name=summary.get("analysis", "Model Explainability and Scenario Analysis"),
            model_name=summary.get("model_name"),
            target=summary.get("target"),
            features=tuple(summary.get("features", [])),
            evaluation_period=summary.get("evaluation_period", {}),
            evaluation_metrics=summary.get("evaluation", {}),
            generated_at_utc=summary.get("generated_at_utc", ""),
            limitations=tuple(summary.get("limitations", [])),
        )

        return self._metadata

    def availability(self) -> tuple[str, tuple[str, ...]]:
        """Check if explainability data is available."""
        try:
            self._load_summary()
            return "available", ()
        except Exception:
            return "unavailable", ("explainability_summary_unavailable",)

    def global_importance(self) -> list[GlobalImportance]:
        """Return permutation feature importance from Notebook 21.

        This importance was computed on a 3000-sample evaluation dataset
        from 2021-2022 using sklearn's permutation_importance with
        neg_mean_absolute_error scoring, 3 repeats, and random_state=42.

        Returns:
            List of feature importance values, sorted by mean MAE increase.
        """
        summary = self._load_summary()
        raw_importance = summary.get("permutation_importance", [])

        return [
            GlobalImportance(
                feature=item["feature"],
                importance_mean_mae_increase=item["importance_mean_mae_increase"],
                importance_std=item["importance_std"],
            )
            for item in raw_importance
        ]

    def evaluation_metrics(self) -> dict[str, Any]:
        """Return evaluation metrics from Notebook 21.

        These metrics were computed on a 3000-sample evaluation dataset
        from 2021-2022. They are sample-specific results, not an
        independent validation.

        Returns:
            Dictionary with MAE, RMSE, R2, and summary statistics.
        """
        summary = self._load_summary()
        return {
            "evaluation": summary.get("evaluation", {}),
            "evaluation_period": summary.get("evaluation_period", {}),
        }

    def crop_season_errors(self) -> list[CropSeasonErrorGroup]:
        """Return crop-season error analysis from Notebook 21.

        Returns the highest-MAE crop-season groups from the evaluation
        sample, with observation counts and error metrics.

        Returns:
            List of crop-season error groups.
        """
        summary = self._load_summary()
        raw_groups = summary.get("highest_mae_groups", [])

        return [
            CropSeasonErrorGroup(
                crop=item["Crop"],
                season=item["Season"],
                observations=item["observations"],
                mae=item["MAE"],
                rmse=item["RMSE"],
            )
            for item in raw_groups
        ]

    def prediction_bias(self) -> tuple[list[PredictionBiasGroup], list[PredictionBiasGroup]]:
        """Return prediction bias analysis from Notebook 21.

        Returns two lists: groups with strongest overprediction and
        groups with strongest underprediction.

        Returns:
            Tuple of (overprediction_groups, underprediction_groups).
        """
        summary = self._load_summary()

        raw_over = summary.get("strongest_overprediction_groups", [])
        raw_under = summary.get("strongest_underprediction_groups", [])

        over_groups = [
            PredictionBiasGroup(
                crop=item["Crop"],
                season=item["Season"],
                observations=item["observations"],
                mean_signed_error=item["mean_signed_error"],
                mean_bias_pct_of_actual=item.get("mean_bias_pct_of_actual"),
            )
            for item in raw_over
        ]

        under_groups = [
            PredictionBiasGroup(
                crop=item["Crop"],
                season=item["Season"],
                observations=item["observations"],
                mean_signed_error=item["mean_signed_error"],
                mean_bias_pct_of_actual=item.get("mean_bias_pct_of_actual"),
            )
            for item in raw_under
        ]

        return over_groups, under_groups

    def scenario_baseline(self) -> ScenarioBaseline:
        """Return the baseline scenario used in Notebook 21.

        This is the specific crop-season-location-year combination used
        for year-based scenario comparisons in the notebook.

        Returns:
            ScenarioBaseline with baseline features and prediction.
        """
        summary = self._load_summary()
        raw_baseline = summary.get("scenario_analysis", {}).get("baseline_features", {})
        baseline_prediction = summary.get("scenario_analysis", {}).get("baseline_prediction", 0.0)

        return ScenarioBaseline(
            crop=raw_baseline.get("Crop", ""),
            season=raw_baseline.get("Season", ""),
            crop_category=raw_baseline.get("Crop_Category", ""),
            state=raw_baseline.get("State", ""),
            district=raw_baseline.get("District", ""),
            fe_year_start=raw_baseline.get("FE_YearStart", 0),
            baseline_prediction=baseline_prediction,
        )

    def metadata(self) -> ExplainabilityMetadata:
        """Return explainability metadata."""
        return self._get_metadata()

    def uncertainty_status(self) -> dict[str, Any]:
        """Return uncertainty calibration status.

        Notebook 21 did not implement prediction interval calibration.
        This method explicitly reports uncertainty as unavailable.

        Returns:
            Dictionary explaining why uncertainty is unavailable.
        """
        return {
            "prediction_interval_available": False,
            "confidence_calibration_available": False,
            "reason": (
                "Notebook 21 (Model Explainability and Scenario Analysis) "
                "did not implement prediction interval calibration or "
                "confidence estimation. No validated uncertainty method "
                "is available from the existing research."
            ),
            "notebook_coverage": "Not implemented",
            "limitations": [
                "No time-aware calibration using out-of-sample residuals was performed.",
                "No conformal prediction experiments were conducted.",
                "No validation of interval coverage or width was performed.",
                "Prediction uncertainty is not supported by the current model research.",
            ],
        }
