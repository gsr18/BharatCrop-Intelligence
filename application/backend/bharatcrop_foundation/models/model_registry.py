from __future__ import annotations

import hashlib
import json
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import pandas as pd


@dataclass(frozen=True)
class ModelCard:
    registry_id: str
    component_type: str
    task: str | None
    target: str | None
    model_name: str | None
    artifact_path: str | None
    metadata_path: str | None
    artifact_exists: bool
    metadata_exists: bool
    recorded_status: str
    registry_disposition: str
    evidence_status: str
    restrictions: str
    artifact_sha256: str | None


@dataclass(frozen=True)
class PolicyRule:
    policy_id: str
    scope: str
    rule: str
    severity: str
    condition: str
    action: str


@dataclass(frozen=True)
class EvaluationEvidence:
    evaluation_period: list[int] | None
    eligible_rows: int | None
    evaluated_groups: int | None
    top1_hit_rate: float | None
    top3_hit_rate: float | None
    mean_spearman_correlation: float | None
    interpretation: str | None
    production_approval: str
    registry_id: str | None = None


class ModelRegistryService:
    """Service for model registry and governance from Notebook 22.

    This service loads and serves the model registry, policy rules,
    and validation status generated by Notebook 22:
    Model Registry and Policy Outputs.

    It does NOT perform real-time registry computations. All results
    are from the original notebook analysis.
    """

    def __init__(
        self,
        registry_dir: Path,
    ) -> None:
        self._registry_dir = registry_dir
        self._registry_df: pd.DataFrame | None = None
        self._policy_rules: list[PolicyRule] | None = None
        self._validation_status: dict[str, Any] | None = None
        self._ranking_evidence: dict[str, Any] | None = None

    def _load_registry(self) -> pd.DataFrame:
        if self._registry_df is not None:
            return self._registry_df

        registry_path = self._registry_dir / "model_registry.csv"
        if not registry_path.exists():
            raise FileNotFoundError(f"Registry not found: {registry_path}")

        self._registry_df = pd.read_csv(registry_path)
        return self._registry_df

    def _load_policy_rules(self) -> list[PolicyRule]:
        if self._policy_rules is not None:
            return self._policy_rules

        policy_path = self._registry_dir / "model_policy_rules.json"
        if not policy_path.exists():
            raise FileNotFoundError(f"Policy rules not found: {policy_path}")

        with open(policy_path, "r", encoding="utf-8") as f:
            policy_data = json.load(f)

        self._policy_rules = [
            PolicyRule(
                policy_id=item["policy_id"],
                scope=item["scope"],
                rule=item["rule"],
                severity=item["severity"],
                condition=item["condition"],
                action=item["action"],
            )
            for item in policy_data
        ]
        return self._policy_rules

    def _load_validation_status(self) -> dict[str, Any]:
        if self._validation_status is not None:
            return self._validation_status

        status_path = self._registry_dir / "model_validation_status_summary.json"
        if not status_path.exists():
            raise FileNotFoundError(f"Validation status not found: {status_path}")

        with open(status_path, "r", encoding="utf-8") as f:
            self._validation_status = json.load(f)
        return self._validation_status

    def _load_ranking_evidence(self) -> dict[str, Any]:
        if self._ranking_evidence is not None:
            return self._ranking_evidence

        evidence_path = self._registry_dir / "crop_recommendation_evaluation_evidence.json"
        if not evidence_path.exists():
            raise FileNotFoundError(f"Ranking evidence not found: {evidence_path}")

        with open(evidence_path, "r", encoding="utf-8") as f:
            self._ranking_evidence = json.load(f)
        return self._ranking_evidence

    def _compute_sha256(self, path: Path) -> str | None:
        if not path.exists():
            return None
        try:
            digest = hashlib.sha256()
            with path.open("rb") as stream:
                for block in iter(lambda: stream.read(1024 * 1024), b""):
                    digest.update(block)
            return digest.hexdigest()
        except OSError:
            return None

    def availability(self) -> tuple[str, tuple[str, ...]]:
        """Check if registry data is available."""
        try:
            self._load_registry()
            return "available", ()
        except Exception:
            return "unavailable", ("registry_unavailable",)

    def portfolio(self) -> list[ModelCard]:
        """Return all model cards from the registry.

        Returns:
            List of ModelCard objects representing all registered components.
        """
        registry_df = self._load_registry()
        project_root = Path(__file__).resolve().parents[4]

        cards = []
        for _, row in registry_df.iterrows():
            artifact_path = None
            if pd.notna(row.get("artifact_path")):
                artifact_path = project_root / row["artifact_path"]

            metadata_path = None
            if pd.notna(row.get("metadata_path")):
                metadata_path = project_root / row["metadata_path"]

            artifact_sha256 = self._compute_sha256(artifact_path) if artifact_path else None

            cards.append(
                ModelCard(
                    registry_id=row["registry_id"],
                    component_type=row["component_type"],
                    task=row.get("task"),
                    target=row.get("target"),
                    model_name=row.get("model_name"),
                    artifact_path=str(row.get("artifact_path")) if pd.notna(row.get("artifact_path")) else None,
                    metadata_path=str(row.get("metadata_path")) if pd.notna(row.get("metadata_path")) else None,
                    artifact_exists=bool(row.get("artifact_exists", False)),
                    metadata_exists=bool(row.get("metadata_exists", False)),
                    recorded_status=row.get("recorded_status", "UNKNOWN"),
                    registry_disposition=row.get("registry_disposition", "UNKNOWN"),
                    evidence_status=row.get("evidence_status", "UNKNOWN"),
                    restrictions=row.get("restrictions", ""),
                    artifact_sha256=artifact_sha256,
                )
            )

        return cards

    def model_card(self, registry_id: str) -> ModelCard | None:
        """Return a specific model card by registry ID.

        Args:
            registry_id: The registry ID to look up.

        Returns:
            ModelCard if found, None otherwise.
        """
        cards = self.portfolio()
        for card in cards:
            if card.registry_id == registry_id:
                return card
        return None

    def evaluation_evidence(self, registry_id: str) -> EvaluationEvidence | None:
        """Return evaluation evidence for a specific component.

        Args:
            registry_id: The registry ID to look up.

        Returns:
            EvaluationEvidence if available, None otherwise.
        """
        if registry_id == "crop_recommendation":
            evidence = self._load_ranking_evidence()
            return EvaluationEvidence(
                registry_id=evidence.get("registry_id", registry_id),
                evaluation_period=evidence.get("evaluation_period"),
                eligible_rows=evidence.get("eligible_prediction_rows"),
                evaluated_groups=evidence.get("evaluated_groups"),
                top1_hit_rate=evidence.get("top1_hit_rate"),
                top3_hit_rate=evidence.get("top3_hit_rate"),
                mean_spearman_correlation=evidence.get("mean_spearman_correlation"),
                interpretation=evidence.get("interpretation"),
                production_approval=evidence.get("production_approval", "NOT ESTABLISHED"),
            )
        return None

    def policy_rules(self) -> list[PolicyRule]:
        """Return all governance policy rules.

        Returns:
            List of PolicyRule objects.
        """
        return self._load_policy_rules()

    def validation_status(self) -> dict[str, Any]:
        """Return overall validation status summary.

        Returns:
            Dictionary with registry counts, policy counts, and component status.
        """
        return self._load_validation_status()

    def health(self) -> dict[str, Any]:
        """Return registry health status.

        Returns:
            Dictionary with availability status and artifact counts.
        """
        availability, reasons = self.availability()

        if availability != "available":
            return {
                "status": "unavailable",
                "reason_codes": list(reasons),
            }

        registry_df = self._load_registry()
        policy_rules = self._load_policy_rules()

        return {
            "status": "available",
            "registry_entries": len(registry_df),
            "policy_rules": len(policy_rules),
            "components_with_artifacts": int(registry_df.get("artifact_exists", False).sum()),
            "components_with_metadata": int(registry_df.get("metadata_exists", False).sum()),
            "notebook_reference": "22_model_registry_and_policy_outputs.ipynb",
        }
